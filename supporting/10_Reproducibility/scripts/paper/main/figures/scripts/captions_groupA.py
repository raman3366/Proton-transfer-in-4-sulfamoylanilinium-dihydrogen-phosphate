def fill(template):
    def rep(m):
        key, _, opt = m.group(1).partition('|')
        mm = re.fullmatch(r'(.+)\.(\d+)', key)
        if mm and mm.group(1) in S.facts() and isinstance(S.F(mm.group(1)), list):
            val = S.F(mm.group(1))[int(mm.group(2))]
            s_ = S.num(val, int(opt) if opt and opt.isdigit() else S.facts()[mm.group(1)]['precision'], sign=(opt == '+'))
            S.USED[mm.group(1)]['printed'].append(s_)
            return s_
        if opt == '+':
            return S.txt(key, sign=True)
        if opt == 'abs':
            return S.txt(key).lstrip('−-')
        if opt:
            return S.txt(key, nd=int(opt))
        return S.txt(key)
    out = re.sub(r'<<([^>]+)>>', rep, template)
    assert '<<' not in out and '>>' not in out
    return out


def main():
    # consistency checks behind statements made in words
    assert S.F('proton.eps4.side') == 'O' and S.F('proton.eps8.side') == 'N'
    assert all(S.F(f'fcheck.{k}.dE_O_N') < 0 for k in ('b3lyp', 'wb97xd', 'pbe0', 'm062x', 'mp2'))
    assert S.F('fcheck.pbe0.top_N') < 0 and S.F('fcheck.m062x.top_N') < 0
    assert S.F('fcheck.b3lyp.top_N') > 0 and S.F('fcheck.wb97xd.top_N') > 0 and S.F('fcheck.mp2.top_N') > 0
    assert max(S.F(f'fcheck.{k}.top_N') for k in ('b3lyp', 'wb97xd', 'pbe0', 'm062x', 'mp2')) < S.F('zpe.NH')
    rg = S.F('fcheck.dE_O_N_range')
    assert abs(rg[0] - S.F('fcheck.m062x.dE_O_N')) < 1e-6 and abs(rg[1] - S.F('fcheck.b3lyp.dE_O_N')) < 1e-6
    assert S.F('periodic.iirfix.constraint_held') is True and S.F('proton.periodic.ii.side') == 'N'
    assert S.F('scan.A03.d_NH') == S.F('scan.B03.d_NH') == 1.35
    assert S.F('xray.n_hbonds') == 9 and S.F('model.M1.n_atoms') == 27
    assert S.F('xray.symop_1_554') == 'x, y, z − 1'
    blocks = [BEGIN, '', '## Group A: structure and proton story (Figs. 1–4)', '']
    for label, stem, where, tpl in CAPTIONS:
        assert (S.FIG / f'{stem}.png').exists(), stem
        blocks += [f'### {stem} {{#{label}}}', '', f'Placement: {where}. File: `figures/{stem}.png`.', '',
                   fill(tpl), '']
    blocks += [fill(NOTES), END]
    text = '\n'.join(blocks) + '\n'
    path = S.FIG / 'captions.md'
    old = path.read_text() if path.exists() else ''
    if BEGIN in old and END in old:
        a, b = old.index(BEGIN), old.index(END) + len(END)
        new = old[:a] + text.rstrip('\n') + old[b:]
    else:
        head = '' if old else ('# Figure captions (master copy)\n\nEach figure group keeps its own block between its '
                               'markers; edit captions through the group scripts.\n\n')
        new = (old.rstrip('\n') + '\n\n' if old else head) + text
    path.write_text(new)
    S.write_used('captions_groupA')
    (S.FIG / 'captions_groupA.facts.json').unlink(missing_ok=True)
    print('wrote', path.relative_to(S.REPO))


if __name__ == '__main__':
    main()
